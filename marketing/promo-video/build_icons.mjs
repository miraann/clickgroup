// Builds icons.js (lucide icon paths, taken from the website's lucide-react) and assets/qr.svg.
//   node build_icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const LUCIDE = path.join(HERE, '../../node_modules/lucide-react/dist/esm/icons');
const NAMES = [
  'globe', 'monitor', 'laptop', 'smartphone', 'tablet', 'calendar', 'calendar-check', 'clock', 'utensils-crossed',
  'chef-hat', 'chart-column', 'qr-code', 'truck', 'map-pin', 'bell-ring', 'check', 'circle-check', 'circle-check-big',
  'phone', 'scan-face', 'shield-check', 'zap', 'languages', 'layout-dashboard', 'sparkles', 'users', 'user', 'code-xml',
  'rocket', 'award', 'receipt', 'shopping-bag', 'credit-card', 'timer', 'navigation', 'store', 'wifi', 'signal',
  'battery-full', 'arrow-left', 'plus', 'search', 'house', 'settings', 'trending-up', 'clipboard-list', 'package',
  'image', 'lightbulb', 'mouse-pointer-click', 'bike', 'flame', 'coffee', 'pizza', 'sandwich', 'cup-soda', 'cake-slice',
  'salad', 'beef', 'ice-cream-cone', 'menu', 'x', 'scissors', 'ticket', 'chevron-left', 'star', 'briefcase-business',
];

const attr = s => [...s.matchAll(/(\w+): "([^"]*)"/g)].filter(([, k]) => k !== 'key')
  .map(([, k, v]) => `${k.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}="${v}"`).join(' ');
const icons = {}, missing = [];
for (const n of NAMES) {
  const f = path.join(LUCIDE, n + '.js');
  if (!fs.existsSync(f)) { missing.push(n); continue; }
  const src = fs.readFileSync(f, 'utf8');
  icons[n] = [...src.matchAll(/\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]/g)].map(([, tag, a]) => `<${tag} ${attr(a)}/>`).join('');
  if (!icons[n]) missing.push(n + ' (empty)');
}
if (missing.length) console.warn('missing icons:', missing.join(', '));
fs.writeFileSync(path.join(HERE, 'icons.js'), `// generated by build_icons.mjs (lucide, ISC licence)\nconst ICONS = ${JSON.stringify(icons)};\n`);

const svg = await QRCode.toString('https://clickgroup.site', { type: 'svg', margin: 0, errorCorrectionLevel: 'M', color: { dark: '#0f172a', light: '#ffffff' } });
fs.writeFileSync(path.join(HERE, 'assets/qr.svg'), svg);
console.log(`icons.js: ${Object.keys(icons).length} icons, assets/qr.svg written`);
